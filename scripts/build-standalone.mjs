/*
 * Build the browser-safe classic-script entry used by index.html.
 *
 * Why this exists: a page opened with file:// cannot reliably load ES modules
 * in Chromium. The maintainable source stays in src/, while this tiny bundler
 * emits a dependency-ordered classic script that works both from file:// and
 * from a local HTTP server. It never minifies or transforms runtime logic.
 */

import { readFile, writeFile } from "node:fs/promises";

const root = new URL("../", import.meta.url);
const modules = [
  "src/data/archive-adapter.js",
  "src/ui/icons.js",
  "src/ui/markdown.js",
  "src/ui/conversation-view.js",
  "src/main.js",
];

function stripModuleSyntax(source) {
  return source
    .replace(/^import\s+[^;]+;\s*$/gm, "")
    .replace(/^export\s+/gm, "");
}

const parts = await Promise.all(modules.map(async (path) => {
  const source = await readFile(new URL(path, root), "utf8");
  return `\n/* ${path} */\n${stripModuleSyntax(source).trim()}\n`;
}));

const output = `/*
 * Generated by scripts/build-standalone.mjs.
 * Edit src/ modules, then run: node scripts/build-standalone.mjs
 */
(function bootstrapLocalArchiveViewer() {
  "use strict";
${parts.join("\n")}
  bootstrap();
}());
`;

await writeFile(new URL("app.js", root), output, "utf8");

const indexUrl = new URL("index.html", root);
const index = await readFile(indexUrl, "utf8");
const katex = await readFile(new URL("src/vendor/katex/katex.min.js", root), "utf8");
// A literal closing script tag ends a raw-text script element even when it is
// inside JavaScript source. Escape it before embedding the project runtime.
const embeddedRuntime = `${katex}\n${output}`.replace(/<\/script/gi, "<\\/script");
const spriteFiles = {};
for (const name of ["sprites-core-26c3f2d4.svg", "sprites-shell-097001e7.svg"]) {
  spriteFiles[`./reference/${name}`] = await readFile(new URL(`reference/${name}`, root), "utf8");
}
const mimeTypes = { ".css": "text/css", ".woff": "font/woff", ".woff2": "font/woff2", ".ttf": "font/ttf" };
const cssSeen = new Set();
const rootPath = new URL(root).pathname;
const projectRelative = (url) => url.pathname.startsWith(rootPath) ? url.pathname.slice(rootPath.length) : url.pathname.replace(/^\//, "");
async function bundleCss(relativePath) {
  if (cssSeen.has(relativePath)) return "";
  cssSeen.add(relativePath);
  const cssUrl = new URL(relativePath, root);
  let css = await readFile(cssUrl, "utf8");
  const imports = [...css.matchAll(/@import\s+url\((['"]?)([^'")]+)\1\)\s*;/g)];
  for (const match of imports) {
    const imported = await bundleCss(projectRelative(new URL(match[2], cssUrl)));
    css = css.replace(match[0], imported);
  }
  const assets = [...new Set([...css.matchAll(/url\((['"]?)([^'")]+)\1\)/g)].map((match) => match[2]))];
  for (const assetPath of assets) {
    if (assetPath.startsWith("data:") || assetPath.startsWith("#")) continue;
    const assetUrl = new URL(assetPath, cssUrl);
    const ext = assetUrl.pathname.match(/\.[^.]+$/)?.[0].toLowerCase() || "";
    let bytes;
    try {
      bytes = await readFile(assetUrl);
    } catch {
      // KaTeX's distributed CSS uses fonts/, while this local vendor folder
      // keeps the font files alongside katex.min.css.
      bytes = await readFile(new URL(assetUrl.pathname.split("/").pop(), cssUrl));
    }
    const dataUrl = `data:${mimeTypes[ext] || "application/octet-stream"};base64,${Buffer.from(bytes).toString("base64")}`;
    css = css.split(assetPath).join(dataUrl);
  }
  return css;
}
const bundledStyles = `${await bundleCss("styles.css")}\n${await bundleCss("src/vendor/katex/katex.min.css")}`;
const runtimeMarker = /(<script id="project-runtime-source" type="text\/plain">)[\s\S]*?(<\/script>)/;
if (!runtimeMarker.test(index)) throw new Error("index.html 缺少 project-runtime-source 占位符");
let nextIndex = index.replace(
  runtimeMarker,
  (_match, start, end) => `${start}${embeddedRuntime}${end}`,
);
const spritePayload = JSON.stringify(spriteFiles).replace(/</g, "\\u003c");
const stylePayload = bundledStyles.replace(/<\/script/gi, "<\\/script");
if (nextIndex.includes('id="project-style-source"')) {
  nextIndex = nextIndex.replace(/(<script id="project-style-source" type="text\/plain">)[\s\S]*?(<\/script>)/, (_match, start, end) => `${start}${stylePayload}${end}`);
} else {
  nextIndex = nextIndex.replace("  </body>", `    <script id="project-style-source" type="text/plain">${stylePayload}</script>\n  </body>`);
}
const completeIndex = nextIndex.includes('id="project-sprite-source"')
  ? nextIndex.replace(/(<script id="project-sprite-source" type="application\/json">)[\s\S]*?(<\/script>)/, (_match, start, end) => `${start}${spritePayload}${end}`)
  : nextIndex.replace("  </body>", `    <script id="project-sprite-source" type="application/json">${spritePayload}</script>\n  </body>`);
await writeFile(indexUrl, completeIndex, "utf8");
